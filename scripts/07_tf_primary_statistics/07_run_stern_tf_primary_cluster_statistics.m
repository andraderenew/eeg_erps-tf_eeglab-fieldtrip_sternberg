ignore_data = cell(1, n_subjects);

for s = 1:n_subjects
    memorize = [];
    memorize.label = labels(:);
    memorize.freq = freq_hz;
    memorize.time = time_s;
    memorize.powspctrm = squeeze( ...
        tf_db(memorize_index, s, :, :, :));
    memorize.dimord = 'chan_freq_time';
    memorize.elec = elec;

    ignore = [];
    ignore.label = labels(:);
    ignore.freq = freq_hz;
    ignore.time = time_s;
    ignore.powspctrm = squeeze( ...
        tf_db(ignore_index, s, :, :, :));
    ignore.dimord = 'chan_freq_time';
    ignore.elec = elec;

    memorize_data{s} = memorize;
    ignore_data{s} = ignore;
end

