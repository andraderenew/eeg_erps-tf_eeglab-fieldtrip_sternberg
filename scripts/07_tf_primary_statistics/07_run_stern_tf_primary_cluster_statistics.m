        pvalue_display, ...
        cluster_statistic, ...
        significant, ...
        time_start_s, ...
        time_end_s, ...
        frequency_start_hz, ...
        frequency_end_hz, ...
        n_channel_frequency_time_samples, ...
        n_channels, ...
        channels, ...
        peak_t, ...
        peak_channel, ...
        peak_frequency_hz, ...
        peak_time_s};
