xline(0, '--', 'Color', [1 1 1], ...
    'HandleVisibility', 'off');
xlabel('Time (s)');
ylabel('Frequency (Hz)');
title([ ...
    'Memorize - Ignore: channels belonging to corrected clusters']);
colorbar;
set(gca, 'FontSize', 13);

