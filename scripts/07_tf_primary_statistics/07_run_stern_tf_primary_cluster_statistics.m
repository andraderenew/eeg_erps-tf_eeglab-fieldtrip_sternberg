close(fig);

fprintf('\n=== CREATING REPRESENTATIVE CLUSTER FIGURES ===\n');

representative_tfr_figure = fullfile( ...
    figure_dir, ...
    'stern_tf_Memorize_minus_Ignore_representative_channel.png');

