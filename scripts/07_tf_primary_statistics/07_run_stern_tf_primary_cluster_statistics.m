function result = summarize_tf_clusters( ...
    stat, ...
    contrast_name, ...
    alpha, ...
    exact_permutations)

    contrast = strings(0, 1);
    sign_name = strings(0, 1);
    cluster_index = [];
    pvalue = [];
    pvalue_display = strings(0, 1);
    cluster_statistic = [];
    significant = [];
    time_start_s = [];
    time_end_s = [];
    frequency_start_hz = [];
    frequency_end_hz = [];
    n_channel_frequency_time_samples = [];
    n_channels = [];
    channels = strings(0, 1);
    peak_t = [];
    peak_channel = strings(0, 1);
    peak_frequency_hz = [];
    peak_time_s = [];

    if isfield(stat, 'posclusters') && ~isempty(stat.posclusters)
        for idx = 1:numel(stat.posclusters)
            mask = stat.posclusterslabelmat == idx;
            cluster = stat.posclusters(idx);

            [ ...
                contrast, ...
                sign_name, ...
                cluster_index, ...
                pvalue, ...
                pvalue_display, ...
                cluster_statistic, ...
                significant, ...
                time_start_s, ...
                time_end_s, ...
                frequency_start_hz, ...
                frequency_end_hz, ...
                n_channel_frequency_time_samples, ...
                n_channels, ...
                channels, ...
                peak_t, ...
                peak_channel, ...
                peak_frequency_hz, ...
                peak_time_s ...
            ] = append_tf_cluster( ...
                stat, ...
                mask, ...
                contrast_name, ...
                'positive', ...
                idx, ...
                cluster.prob, ...
                cluster.clusterstat, ...
                alpha, ...
                exact_permutations, ...
                contrast, ...
                sign_name, ...
                cluster_index, ...
                pvalue, ...
                pvalue_display, ...
                cluster_statistic, ...
                significant, ...
                time_start_s, ...
                time_end_s, ...
                frequency_start_hz, ...
                frequency_end_hz, ...
                n_channel_frequency_time_samples, ...
                n_channels, ...
                channels, ...
                peak_t, ...
                peak_channel, ...
                peak_frequency_hz, ...
                peak_time_s);
        end
    end

    if isfield(stat, 'negclusters') && ~isempty(stat.negclusters)
        for idx = 1:numel(stat.negclusters)
            mask = stat.negclusterslabelmat == idx;
            cluster = stat.negclusters(idx);

            [ ...
                contrast, ...
                sign_name, ...
                cluster_index, ...
                pvalue, ...
                pvalue_display, ...
                cluster_statistic, ...
                significant, ...
                time_start_s, ...
                time_end_s, ...
                frequency_start_hz, ...
                frequency_end_hz, ...
                n_channel_frequency_time_samples, ...
                n_channels, ...
                channels, ...
                peak_t, ...
                peak_channel, ...
                peak_frequency_hz, ...
                peak_time_s ...
            ] = append_tf_cluster( ...
                stat, ...
                mask, ...
                contrast_name, ...
                'negative', ...
                idx, ...
                cluster.prob, ...
                cluster.clusterstat, ...
                alpha, ...
                exact_permutations, ...
                contrast, ...
                sign_name, ...
                cluster_index, ...
                pvalue, ...
                pvalue_display, ...
                cluster_statistic, ...
                significant, ...
                time_start_s, ...
                time_end_s, ...
                frequency_start_hz, ...
                frequency_end_hz, ...
                n_channel_frequency_time_samples, ...
                n_channels, ...
                channels, ...
                peak_t, ...
                peak_channel, ...
                peak_frequency_hz, ...
                peak_time_s);
        end
    end

    result = table( ...
        contrast, ...
        sign_name, ...
        cluster_index, ...
        pvalue, ...
        pvalue_display, ...
        cluster_statistic, ...
        logical(significant), ...
        time_start_s, ...
        time_end_s, ...
        frequency_start_hz, ...
        frequency_end_hz, ...
        n_channel_frequency_time_samples, ...
        n_channels, ...
        channels, ...
        peak_t, ...
        peak_channel, ...
        peak_frequency_hz, ...
        peak_time_s, ...
        'VariableNames', { ...
            'contrast', ...
            'sign', ...
            'cluster_index', ...
            'pvalue', ...
            'pvalue_display', ...
            'cluster_statistic', ...
            'significant_p_lt_0_05', ...
            'time_start_s', ...
            'time_end_s', ...
            'frequency_start_hz', ...
            'frequency_end_hz', ...
            'n_channel_frequency_time_samples', ...
            'n_channels', ...
            'channels', ...
            'peak_t', ...
            'peak_channel', ...
            'peak_frequency_hz', ...
            'peak_time_s'});
end

function varargout = append_tf_cluster( ...
    stat, ...
    mask, ...
    contrast_name, ...
    cluster_sign, ...
    index, ...
    probability, ...
    cluster_stat, ...
    alpha, ...
    exact_permutations, ...
    contrast, ...
    sign_name, ...
    cluster_index, ...
    pvalue, ...
    pvalue_display, ...
    cluster_statistic, ...
    significant, ...
    time_start_s, ...
    time_end_s, ...
    frequency_start_hz, ...
    frequency_end_hz, ...
    n_channel_frequency_time_samples, ...
    n_channels, ...
    channels, ...
    peak_t, ...
    peak_channel, ...
    peak_frequency_hz, ...
    peak_time_s)

    [channel_indices, frequency_indices, time_indices] = ...
        ind2sub(size(mask), find(mask));

    unique_channel_indices = unique(channel_indices);
    unique_frequency_indices = unique(frequency_indices);
    unique_time_indices = unique(time_indices);

    cluster_t = stat.stat;
    cluster_t(~mask) = NaN;

    if strcmp(cluster_sign, 'positive')
        [peak_value, peak_linear_index] = max( ...
            cluster_t, ...
            [], ...
            'all', ...
            'omitnan', ...
            'linear');
    else
        [peak_value, peak_linear_index] = min( ...
            cluster_t, ...
            [], ...
            'all', ...
            'omitnan', ...
            'linear');
    end

    [peak_channel_index, peak_frequency_index, peak_time_index] = ...
        ind2sub(size(stat.stat), peak_linear_index);

    contrast(end+1, 1) = string(contrast_name);
    sign_name(end+1, 1) = string(cluster_sign);
    cluster_index(end+1, 1) = index;
    pvalue(end+1, 1) = probability;

    if probability == 0
        pvalue_display(end+1, 1) = ...
            string(sprintf('< %.6f', 1 / exact_permutations));
    else
        pvalue_display(end+1, 1) = ...
            string(sprintf('%.6f', probability));
    end

    cluster_statistic(end+1, 1) = cluster_stat;
    significant(end+1, 1) = probability < alpha;
    time_start_s(end+1, 1) = ...
        min(stat.time(unique_time_indices));
    time_end_s(end+1, 1) = ...
        max(stat.time(unique_time_indices));
    frequency_start_hz(end+1, 1) = ...
        min(stat.freq(unique_frequency_indices));
    frequency_end_hz(end+1, 1) = ...
        max(stat.freq(unique_frequency_indices));
    n_channel_frequency_time_samples(end+1, 1) = nnz(mask);
    n_channels(end+1, 1) = numel(unique_channel_indices);
    channels(end+1, 1) = strjoin( ...
        string(stat.label(unique_channel_indices)), ...
        ',');
    peak_t(end+1, 1) = peak_value;
    peak_channel(end+1, 1) = ...
        string(stat.label{peak_channel_index});
    peak_frequency_hz(end+1, 1) = ...
        stat.freq(peak_frequency_index);
    peak_time_s(end+1, 1) = ...
        stat.time(peak_time_index);

    varargout = { ...
        contrast, ...
        sign_name, ...
