cfg.frequency        = [4 30];
cfg.latency          = [0 1.4];
cfg.parameter        = 'powspctrm';
cfg.method           = 'montecarlo';
cfg.statistic        = 'ft_statfun_depsamplesT';
cfg.correctm         = 'cluster';
cfg.clusteralpha     = 0.05;
cfg.clusterstatistic = 'maxsum';
cfg.minnbchan        = 2;
cfg.neighbours       = neighbours;
cfg.tail             = 0;
cfg.clustertail      = 0;
cfg.alpha            = 0.05;
cfg.correcttail      = 'alpha';
cfg.numrandomization = 'all';

design = zeros(2, 2 * n_subjects);
design(1, :) = [1:n_subjects 1:n_subjects];
design(2, :) = [ ...
    ones(1, n_subjects) ...
    2 .* ones(1, n_subjects)];

cfg.design = design;
cfg.uvar = 1;
cfg.ivar = 2;

stat = ft_freqstatistics( ...
    cfg, ...
    memorize_data{:}, ...
    ignore_data{:});

stat_file = fullfile( ...
    mat_dir, ...
    'stern_tf_cluster_Memorize_minus_Ignore.mat');

save(stat_file, 'stat', '-v7.3');

fprintf('\n=== SUMMARIZING TF CLUSTERS ===\n');

cluster_table = summarize_tf_clusters( ...
    stat, ...
    'Memorize_minus_Ignore', ...
    0.05, ...
    8192);

cluster_table_file = fullfile( ...
    table_dir, ...
    'stern_tf_cluster_Memorize_minus_Ignore.tsv');

writetable( ...
    cluster_table, ...
    cluster_table_file, ...
    'FileType', 'text', ...
    'Delimiter', '\t');

significant_cluster_count = sum( ...
    cluster_table.significant_p_lt_0_05);

fprintf('CLUSTERS_TOTAL=%d\n', height(cluster_table));
fprintf('CLUSTERS_SIGNIFICANT=%d\n', significant_cluster_count);

fprintf('\n=== CREATING PRIMARY DIFFERENCE FIGURE ===\n');

difference = squeeze(mean( ...
    tf_db(memorize_index, :, :, :, :) - ...
    tf_db(ignore_index, :, :, :, :), ...
    [2 3], ...
    'omitnan'));
% frequency x time

significant_mask = false(size(stat.stat));
if isfield(stat, 'mask')
    significant_mask = logical(stat.mask);
end

significant_channel_count = squeeze(sum(significant_mask, 1));
any_significant = significant_channel_count > 0;

difference_limit = max(abs(difference), [], 'all');
