fprintf(fid, 'QC figure: %s\n', qc_figure_file);
fprintf(fid, '\nInterpretation constraint:\n');
fprintf(fid, ...
    ['Memorize - Ignore is the primary event-matched letter-onset ' ...
     'contrast. Probe comparisons are treated as task-phase contrasts.\n']);

fclose(fid);

