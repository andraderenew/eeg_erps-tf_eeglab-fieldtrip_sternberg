fprintf(fid, 'EEGLAB version: %s\n', eeg_getversion);
fprintf(fid, 'MATLAB version: %s\n', version);
fprintf(fid, 'FieldTrip directory: %s\n', fieldtrip_dir);
fprintf(fid, 'Subjects: %d\n', n_subjects);
fprintf(fid, 'Conditions: %s\n', strjoin(conditions, ', '));
fprintf(fid, 'Scalp EEG channels: %d\n', n_channels);
fprintf(fid, 'Eye channels excluded: LEYE, REYE\n');
fprintf(fid, 'Frequency method: mtmconvol with Hanning taper\n');
fprintf(fid, 'Frequencies: %s Hz\n', mat2str(freq_hz));
fprintf(fid, 'Cycles per frequency: %d\n', cycles_per_frequency);
fprintf(fid, 'Times: %.2f to %.2f s in %.2f s steps\n', ...
    min(time_s), max(time_s), median(diff(time_s)));
fprintf(fid, 'Baseline: %.2f to %.2f s\n', ...
    baseline_window(1), baseline_window(2));
fprintf(fid, 'Baseline type: dB\n');
fprintf(fid, 'TFR array order: condition x subject x channel x frequency x time\n');
fprintf(fid, 'TFR array size: %s\n', mat2str(size(tf_db)));
fprintf(fid, 'TFR non-finite count: %d\n', ...
    sum(~isfinite(tf_db), 'all'));
fprintf(fid, 'Total trials represented: %d\n', sum(qc_trials));
fprintf(fid, 'Total rejected ICA components removed: %d\n', ...
    sum(qc_rejected_ics));
fprintf(fid, 'Datasets with interpolated scalp channels: %d\n', ...
    sum(qc_missing_scalp_channels > 0));
fprintf(fid, 'Subject-level TFR: %s\n', subject_tfr_file);
